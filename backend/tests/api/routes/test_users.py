@pytest.mark.parametrize(
    "method, path",
    [
        ("GET", "/"),
        ("POST", "/"),
        ("GET", "/{id}"),
        ("PATCH", "/{id}"),
        ("DELETE", "/{id}"),
        ("PATCH", "/me"),
        ("DELETE", "/me"),
    ],
)
def test_template_user_endpoints_removed(
    client: TestClient, superuser_token_headers: dict[str, str], method: str, path: str
) -> None:
    response = client.request(
        method,
        f"{settings.API_V1_STR}/users{path.format(id=uuid4())}",
        headers=superuser_token_headers,
        json={},
    )
    assert response.status_code == 404
